#회원정보 테이블 생성문

CREATE TABLE SHOP_MEMBER (
	MEM_EMAIL VARCHAR(50) PRIMARY KEY
	, MEM_PW VARCHAR(50) NOT NULL
	, MEM_NAME VARCHAR(30) NOT NULL
	, MEM_TEL VARCHAR(15) NOT NULL UNIQUE #'010-1111-2222'
	, MEM_ADDR VARCHAR(50)
	, ADDR_DETAIL VARCHAR(100)
	, IS_USING VARCHAR(10) DEFAULT 'Y'  #'Y' : 사용중, 'N' : 사용 안 함
	, MEM_ROLE VARCHAR(20) DEFAULT 'USER'  #USER : 회원, MANAGER : 쇼핑몰 운영자, ADMIN : 관리자
	, JOIN_DATE DATETIME DEFAULT SYSDATE()
);

UPDATE SHOP_MEMBER
SET
	MEM_EMAIL = 'manager'
	, MEM_PW = '1111'
	, MEM_ROLE = 'MANAGER'
WHERE MEM_EMAIL = 'qoreogns3';

SELECT * FROM SHOP_MEMBER;

# 가장 최근 등록한 멤버 삭제 쿼리
DELETE FROM SHOP_MEMBER 
WHERE JOIN_DATE = (SELECT MAX(JOIN_DATE) FROM SHOP_MEMBER);

# 도서 카테고리 정보
CREATE TABLE BOOK_CATEGORY(
	CATE_NUM INT PRIMARY KEY AUTO_INCREMENT
	, CATE_NAME VARCHAR(20) NOT NULL UNIQUE
)

