# 도서 정보 테이블
CREATE TABLE SHOP_BOOK (
	BOOK_NUM INT PRIMARY KEY AUTO_INCREMENT
	, BOOK_TITLE VARCHAR(30) NOT NULL
	, AUTHOR VARCHAR(20) NOT NULL 
	, BOOK_PRICE INT NOT NULL
	, BOOK_STOCK INT DEFAULT 10
	, BOOK_INTRO VARCHAR(50)
	, PUBLISH_DATE DATETIME #출판일
	, CATE_NUM INT NOT NULL REFERENCES BOOK_CATEGORY (CATE_NUM)
);

CREATE TABLE BOOK_IMG (
	IMG_NUM INT PRIMARY KEY AUTO_INCREMENT
	, ORIGIN_FILE_NAME VARCHAR(100)
	, UPLOAD_FILE_NAME VARCHAR(100)
	, IS_MAIN VARCHAR(1) NOT NULL
	, BOOK_NUM INT NOT NULL REFERENCES SHOP_BOOK(BOOK_NUM) ON DELETE CASCADE
);

CREATE TABLE SHOP_CART (
	CART_NUM INT PRIMARY KEY AUTO_INCREMENT #장바구니번호
	, BOOK_NUM INT REFERENCES SHOP_BOOK (BOOK_NUM) #상품번호
	, CART_CNT INT NOT NULL #장바구니에 담은 도서 수량 #장바구니에 담은 수량
	, MEM_EMAIL VARCHAR(20) REFERENCES SHOP_MEMBER (MEM_EMAIL) #장바구니 주인 Email
	, CART_DATE DATETIME DEFAULT SYSDATE() #장바구니에 담은 날짜
);

CREATE TABLE SHOP_BUY (
	BUY_NUM INT PRIMARY KEY AUTO_INCREMENT #구매번호
	, BUY_PRICE INT NOT NULL #총구매금액
	, MEM_EMAIL VARCHAR(20) REFERENCES SHOP_MEMBER (MEM_EMAIL) #구매자 Email
	, BUY_DATE DATETIME DEFAULT SYSDATE() #구매일
);

CREATE TABLE BUY_DETAIL (
	BUY_DETAIL_NUM INT PRIMARY KEY AUTO_INCREMENT #구매 상세 번호
	, BOOK_NUM INT REFERENCES SHOP_BOOK (BOOK_NUM) #상품번호
	, BUY_CNT INT NULL NULL #구매수량
	, BUY_PRICE INT NOT NULL #구매금액
	, BUY_NUM INT REFERENCES SHOP_BUY (BUY_NUM) #구매번호
);

